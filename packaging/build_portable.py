def copy_files(origin: Path, destination: Path, names) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    for name in names:
        shutil.copy2(origin / name, destination / name)


def prepare_inputs() -> tuple[Path, dict]:
    """Stage only declared runtime files, never a developer directory tree."""
    clean_owned(BUILD)
    stage = BUILD / 'inputs'
    copy_files(BACKEND, stage, ('server.py', 'settings.py'))
    copy_files(BACKEND / 'physics', stage / 'physics', PHYSICS_FILES)
    copy_files(FRONTEND, stage / 'web', FRONTEND_FILES)
    copy_files(FRONTEND / 'modules', stage / 'web' / 'modules', FRONTEND_MODULES)
    copy_files(FRONTEND / 'chapter1', stage / 'web' / 'chapter1', CHAPTER1_FILES)
    copy_files(FRONTEND / 'assets', stage / 'web' / 'assets', FRONTEND_ASSETS)
    for directory in CHAPTER_DIRS:
        files = sorted(p.name for p in (FRONTEND / directory).iterdir()
                       if p.is_file() and p.suffix in ('.js', '.css', '.html', '.json'))
        copy_files(FRONTEND / directory, stage / 'web' / directory, files)
    shutil.copytree(FRONTEND / 'assets' / 'precomputed', stage / 'web' / 'assets' / 'precomputed')
    copy_files(BACKEND / 'physics' / 'edge_native', stage / 'physics' / 'edge_native', EDGE_FILES)
    three = FRONTEND / 'node_modules' / 'three'
    if not (three / 'package.json').is_file():
        raise FileNotFoundError(f'Three.js must be installed locally: {three}')
    destination = stage / 'web' / 'node_modules' / 'three'
    pending = [three / 'build' / 'three.module.js']
    import_pattern = re.compile(r"\bfrom\s*['\"]([^'\"]+)['\"]")
    for path in (stage / 'web').rglob('*.js'):
        pending.extend(three / 'examples' / 'jsm' / item.removeprefix('three/addons/')
                       for item in import_pattern.findall(path.read_text(encoding='utf-8'))
                       if item.startswith('three/addons/'))
    copied = set()
    while pending:
        path = pending.pop().resolve()
        if path in copied:
            continue
        relative = path.relative_to(three.resolve())
        target = destination / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)
        copied.add(path)
        pending.extend(path.parent / item for item in import_pattern.findall(path.read_text(encoding='utf-8'))
                       if item.startswith('.'))
    copy_files(three, destination, ('LICENSE', 'package.json'))
    licenses = prepare_licenses(three, stage / 'web')
    write_text(stage / 'portable_runtime.py', """import os, sys
from pathlib import Path
for stream in (sys.stdout, sys.stderr):
    if stream is not None and hasattr(stream, 'reconfigure'):
        stream.reconfigure(encoding='utf-8')
sys.dont_write_bytecode = True
data = Path(os.environ.get('LOCALAPPDATA', Path.home() / 'AppData' / 'Local')) / 'MagnetronVirtualLab'
data.mkdir(parents=True, exist_ok=True)
os.environ.setdefault('MAGNETRON_DATA_DIR', str(data))
""")
    return stage, licenses


def build(stage: Path) -> Path:
    clean_owned(DIST / APP_NAME)
    command = [sys.executable, '-m', 'PyInstaller', '--noconfirm', '--clean', '--onedir',
               '--name', APP_NAME, '--distpath', str(DIST), '--workpath', str(BUILD / 'pyinstaller'),
               '--specpath', str(BUILD), '--runtime-hook', str(stage / 'portable_runtime.py'),
               '--add-data', f'{stage / "web"};web', '--add-data', f'{stage / "physics"};physics']
    # Fixed Sobol basis is vendored; finite-edge Laplace solves require SciPy.
    # The build venv is a plain `python -m venv` over the conda base env: its
    # _ctypes.pyd lives in the base DLLs directory and loads ffi-*.dll from
    # the base Library\bin, which PyInstaller never collects. The frozen
    # compute worker then dies with "DLL load failed while importing _ctypes"
    # under the smoke test's stripped PATH. Collect the DLLs explicitly.
    venv_cfg = ROOT / '.portable-build-env' / 'pyvenv.cfg'
    if venv_cfg.is_file():
        home = next((line.split('=', 1)[1].strip() for line in venv_cfg.read_text(encoding='utf-8').splitlines()
                     if line.startswith('home =')), '')
        for ffi_name in ('ffi-8.dll', 'ffi.dll', 'libffi-8.dll'):
            ffi = Path(home) / 'Library' / 'bin' / ffi_name
            if ffi.is_file():
                command += ['--add-binary', f'{ffi};.']
    for module in ('numpy', 'psutil', 'scipy.sparse', 'scipy.sparse.linalg', 'scipy.interpolate'):
        command += ['--hidden-import', module]
    for module in ('matplotlib', 'pandas', 'IPython', 'jupyter', 'torch', 'tensorflow', 'PyQt5',
                   'PyQt6', 'PySide2', 'PySide6', 'tkinter', 'pytest', 'sphinx', 'sympy', 'dask',
                   'distributed', 'zarr', 'PIL', 'cv2', 'sklearn', 'skimage', 'jax', 'cupy', 'numba', 'llvmlite'):
        command += ['--exclude-module', module]
    command += ['--paths', str(BACKEND)]
    command.append(str(BACKEND / 'server.py'))
    subprocess.run(command, cwd=ROOT, check=True)
    folder = DIST / APP_NAME
    record_build_inputs(folder, stage)
    return folder


def record_build_inputs(folder: Path, stage: Path) -> None:
    files = ['server.py', 'settings.py', *[f'physics/{name}' for name in PHYSICS_FILES],
             *[f'physics/edge_native/{name}' for name in EDGE_FILES]]
    records = {name: hashlib.sha256((stage / name).read_bytes()).hexdigest() for name in files}
    write_text(folder / 'build-inputs.json', json.dumps(records, indent=2))


def refresh_web(folder: Path) -> dict:
    records = json.loads((folder / 'build-inputs.json').read_text(encoding='utf-8'))
    changed = [name for name, digest in records.items()
               if hashlib.sha256((BACKEND / name).read_bytes()).hexdigest() != digest]
    if changed:
        raise ValueError(f'Python 源码已变化，需要全量构建：{changed}')
    stage, licenses = prepare_inputs()
    web = folder / '_internal' / 'web'
    clean_owned(web)
    shutil.copytree(stage / 'web', web)
    return licenses


