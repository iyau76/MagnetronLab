def fetch_json(url: str, payload=None):
    raw = None if payload is None else json.dumps(payload).encode()
    request = urllib.request.Request(url, raw, {'Content-Type': 'application/json'})
    with urllib.request.urlopen(request, timeout=5) as response:
        return json.load(response)


def source_reference_counts(payload: dict) -> list:
    """Compare frozen output with this release's geometry, never a historical count."""
    probe = ("import json,sys;sys.path.insert(0,sys.argv[1]);"
             "sys.path.insert(0,str(__import__('pathlib').Path(sys.argv[1]).parent));"
             "import service;from settings import parameters;result=service.execute('point',parameters(json.loads(sys.argv[2])));service.close_cache();print(json.dumps(result['row']['counts']))")
    with tempfile.TemporaryDirectory(prefix='magnetron-source-reference-') as directory:
        result = subprocess.run([sys.executable, '-c', probe, str(BACKEND / 'physics'), json.dumps(payload)],
                                cwd=ROOT, check=True, capture_output=True, text=True, encoding='utf-8',
                                env=os.environ | {'MAGNETRON_DATA_DIR': directory})
    return json.loads(result.stdout.strip().splitlines()[-1])


def smoke_test(folder: Path, port: int) -> dict:
    # Run from a different directory and remove Conda/Python search paths. Every
    # runtime dependency must come from the portable folder or Windows itself.
    log = BUILD / 'portable-smoke.log'
    env = {key: value for key, value in os.environ.items()
           if not key.startswith(('CONDA', 'PYTHON', 'MAMBA', 'NUMBA'))}
    env['PATH'] = str(Path(os.environ['SystemRoot']) / 'System32') + ';' + os.environ['SystemRoot']
    env['LOCALAPPDATA'] = str(BUILD / 'clean-user-data')
    env['PYTHONNOUSERSITE'] = '1'
    env['PYTHONIOENCODING'] = 'utf-8'
    address = f'http://127.0.0.1:{port}'
    started = time.perf_counter()
    with log.open('w', encoding='utf-8') as output:
        process = subprocess.Popen([str(folder / f'{APP_NAME}.exe'), '--port', str(port)],
                                   cwd=DIST, env=env, stdout=output, stderr=output,
                                   creationflags=subprocess.CREATE_NO_WINDOW)
        try:
            deadline = time.monotonic() + 180
            while time.monotonic() < deadline:
                if process.poll() is not None:
                    raise RuntimeError(f'发布程序提前退出，见 {log}')
                try:
                    health = fetch_json(address + '/api/health')
                    if health['worker']['state'] == 'error':
                        raise RuntimeError(health['worker'])
                    if health['worker']['state'] == 'ready':
                        break
                except (urllib.error.URLError, TimeoutError):
                    pass
                time.sleep(.25)
            else:
                raise TimeoutError('发布程序计算核心未在 180 秒内就绪')
            ready_seconds = time.perf_counter() - started
            if health.get('application_id') != 'magnetron-lab-finals-native' or Path(health.get('instance_path','')) != folder.resolve():
                raise AssertionError(f'Wrong running release: {health}')
            resources = {}
            for path in ('/', '/usage.html', '/licenses.html', '/modules/ideal-physics.js',
                         '/chapter1/main.js', '/chapter1/scene.js', '/chapter1/lab-room.js', '/chapter1/book.js',
                         '/chapter1/data.js', '/chapter1/diagrams.js', '/chapter1/chapter.css',
                         '/chapter1/diagrams.css', '/chapter1/book.css', '/chapter1/manual.html', '/chapter1/scene-labels.css',
                         '/chapter1/tube-assembly.js', '/chapter1/scene-labels.js', '/chapter1/coil-lod.js', '/chapter1/instrument-displays.js',
                         '/assets/measurements.json', '/node_modules/three/build/three.module.js',
                         '/node_modules/three/examples/jsm/loaders/GLTFLoader.js', '/assets/bench_optimized.glb'):
                with urllib.request.urlopen(address + path, timeout=15) as response:
                    resources[path] = {'status': response.status, 'bytes': len(response.read())}
            for path in sorted((folder / '_internal' / 'web').rglob('*')):
                if path.is_file() and 'node_modules' not in path.parts and 'licenses' not in path.parts:
                    url = '/' + path.relative_to(folder / '_internal' / 'web').as_posix()
                    with urllib.request.urlopen(address + url, timeout=30) as response:
                        content = response.read()
                    if hashlib.sha256(content).digest() != hashlib.sha256(path.read_bytes()).digest():
                        raise AssertionError(f'Runtime asset mismatch: {url}')
                    resources[url] = {'status': 200, 'bytes': len(content)}
            payload = {'particles': 1024, 'field_mT': 4.2, 'anode_V': 10, 'filament_V': 3.68, 'compute_threads': 1}
            ident = fetch_json(address + '/api/point', payload)['id']
            while time.monotonic() < deadline:
                job = fetch_json(address + '/api/job/' + ident)
                if job['state'] in ('done', 'error', 'cancelled'):
                    break
                time.sleep(.15)
            if job['state'] != 'done':
                raise RuntimeError(job)
            row = job['result']['row']
            if abs(row['sum_uA'] - row['A1_uA'] - row['A2_uA']) > 1e-9:
                raise AssertionError('发布版两路合流不一致')
            expected_counts = source_reference_counts(payload)
            if row['counts'] != expected_counts:
                raise AssertionError(f'发布版统计与已验收开发基准不同：{row["counts"]} != {expected_counts}')
            scan_payload = {**payload, 'fields_mT': [0.0, 4.2]}
            scan_id = fetch_json(address + '/api/scan', scan_payload)['id']
            while time.monotonic() < deadline:
                scan_job = fetch_json(address + '/api/job/' + scan_id)
                if scan_job['state'] in ('done', 'error', 'cancelled'):
                    break
                time.sleep(.05)
            if scan_job['state'] != 'done':
                raise RuntimeError(scan_job)
            scan_rows = scan_job['result']['rows']
            if [item['field_mT'] for item in scan_rows] != [0.0, 4.2]:
                raise AssertionError('Frozen explicit scan grid changed')
            if any(sum(item['counts']) != 1024 for item in scan_rows):
                raise AssertionError('Frozen scan lost particles')
            unwanted = [path.relative_to(folder).as_posix() for path in folder.rglob('*')
                        if path.name.lower().startswith(('numba', 'llvmlite'))]
            if unwanted:
                raise AssertionError(f'Unexpected compiler/scientific runtime payload: {unwanted}')
            result = {'ready_seconds': ready_seconds, 'health': health, 'resources': resources,
                      'params': payload, 'row': row, 'elapsed_s': job['result']['elapsed_s'],
                      'worker_memory_mb': job['result'].get('worker_memory_mb'),
                      'paths_count': len(job['result']['paths']),
                      'reference_counts': expected_counts, 'scan_rows': scan_rows,
                      'runtime_payload_check': 'no numba or llvmlite files; SciPy included for finite-edge fields',
                      'isolation': 'different working directory; PATH only Windows; no Conda/Python variables; fresh local app data',
                      'port': port}
            fetch_json(address + '/api/shutdown', {})
            process.wait(timeout=15)
        finally:
            if process.poll() is None:
                try:
                    fetch_json(address + '/api/shutdown', {})
                    process.wait(timeout=15)
                except (urllib.error.URLError, TimeoutError, subprocess.TimeoutExpired):
                    process.terminate()
                    process.wait(timeout=10)
    log_text = log.read_text(encoding='utf-8', errors='replace')
    if 'Traceback' in log_text or 'Exception ignored' in log_text:
        raise RuntimeError('发布版日志含运行错误，详见 portable-smoke.log')
    write_text(BUILD / 'portable-smoke.json', json.dumps(result, ensure_ascii=False, indent=2))
    return result


def seal(folder: Path, licenses: dict, smoke: dict | None) -> Path:
    manifest = {'application': '磁截止实验室', 'version': 'finals-six-chapters-20261117',
                'platform': 'Windows x86_64', 'dependencies': licenses, 'smoke_test': smoke,
                'files': []}
    for path in sorted(folder.rglob('*')):
        if path.is_file() and path.name != 'release-manifest.json':
            manifest['files'].append({'path': path.relative_to(folder).as_posix(),
                                      'bytes': path.stat().st_size,
                                      'sha256': hashlib.sha256(path.read_bytes()).hexdigest()})
    write_text(folder / 'release-manifest.json', json.dumps(manifest, ensure_ascii=False, indent=2))
    archive = DIST / f'{APP_NAME}-Windows-x64.zip'
    with zipfile.ZipFile(archive, 'w', compression=zipfile.ZIP_DEFLATED, compresslevel=6) as package:
        for path in sorted(folder.rglob('*')):
            if path.is_file():
                package.write(path, f'{APP_NAME}/{path.relative_to(folder).as_posix()}')
    if archive.stat().st_size >= 500_000_000:
        raise RuntimeError(f'发布包超过 500 MB：{archive.stat().st_size}')
    print(json.dumps({'zip': str(archive), 'zip_bytes': archive.stat().st_size,
                      'unpacked_bytes': sum(item['bytes'] for item in manifest['files']),
                      'smoke': smoke}, ensure_ascii=False, indent=2))
    return archive


def verify_archive(archive: Path, port: int) -> dict:
    relocated = BUILD / 'relocated' / 'Offline lab 中文'
    clean_owned(relocated)
    relocated.mkdir(parents=True)
    with zipfile.ZipFile(archive) as package:
        bad_member = package.testzip()
        if bad_member is not None:
            raise ValueError(f'ZIP 校验失败：{bad_member}')
        for member in package.infolist():
            if not (relocated / member.filename).resolve().is_relative_to(relocated.resolve()):
                raise ValueError('ZIP 包含越界路径')
        package.extractall(relocated)
    extracted = relocated / APP_NAME
    manifest = json.loads((extracted / 'release-manifest.json').read_text(encoding='utf-8'))
    for item in manifest['files']:
        target = extracted / item['path']
        if not target.resolve().is_relative_to(extracted.resolve()):
            raise ValueError('Manifest contains an unsafe path')
        if target.stat().st_size != item['bytes'] or hashlib.sha256(target.read_bytes()).hexdigest() != item['sha256']:
            raise ValueError(f'Extracted file does not match manifest: {item["path"]}')
    clean_owned(BUILD / 'clean-user-data')
    result = smoke_test(extracted, port)
    result['archive_sha256'] = hashlib.sha256(archive.read_bytes()).hexdigest()
    result['archive_bytes'] = archive.stat().st_size
    result['relocated_path_test'] = 'ZIP extracted into a different directory with spaces and Chinese characters'
    write_text(BUILD / 'archive-verification.json', json.dumps(result, ensure_ascii=False, indent=2))
    return result


