def clean_owned(path: Path) -> None:
    resolved = path.resolve()
    permitted = (ROOT / 'build').resolve(), DIST.resolve()
    generated_license_directory = (BUILD / 'inputs' / 'web' / 'licenses').resolve()
    if resolved != generated_license_directory and not any(resolved.is_relative_to(parent) and resolved != parent for parent in permitted):
        raise ValueError(f'清理目标不在本项目构建子目录中：{resolved}')
    if resolved.exists():
        shutil.rmtree(resolved)


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')


